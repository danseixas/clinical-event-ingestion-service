import { parseEventTimestamp } from './event-timestamp.js';

describe('parseEventTimestamp', () => {
  it.each([
    ['2026-11-02T13:00:00Z', '2026-11-02T13:00:00.000Z'],
    ['2026-11-02T10:00:00.000-03:00', '2026-11-02T13:00:00.000Z'],
    ['2024-02-29T00:00:00Z', '2024-02-29T00:00:00.000Z'],
    ['1970-01-01T00:00:00Z', '1970-01-01T00:00:00.000Z'],
    ['9999-12-31T23:59:59.999Z', '9999-12-31T23:59:59.999Z'],
    ['2026-11-02T10:00:00.1239Z', '2026-11-02T10:00:00.123Z'],
    ['2026-11-02T10:00:00.1Z', '2026-11-02T10:00:00.100Z'],
    ['2026-11-02T10:00:00.123456789+05:30', '2026-11-02T04:30:00.123Z'],
    ['2026-11-02T10:00:00+23:59', '2026-11-01T10:01:00.000Z'],
    ['2026-11-02T10:00:00-23:59', '2026-11-03T09:59:00.000Z'],
  ])('accepts %s', (input, iso) => {
    expect(parseEventTimestamp(input)?.toISOString()).toBe(iso);
  });

  it.each([
    '2026-11-02T10:00:00',
    '2026-11-02T10:00Z',
    '2026-11-02',
    '2026-11-02t10:00:00Z',
    '2026-11-02T10:00:00z',
    '2026-02-30T00:00:00Z',
    '2023-02-29T00:00:00Z',
    '2026-13-01T00:00:00Z',
    '2026-00-10T00:00:00Z',
    '2026-11-02T24:00:00Z',
    '2026-11-02T10:60:00Z',
    '2026-11-02T10:00:60Z',
    '2026-11-02T10:00:00+24:00',
    '2026-11-02T10:00:00+23:60',
    '2026-11-02T10:00:00.1234567890Z',
    '1969-12-31T23:59:59.999Z',
    '1970-01-01T00:30:00+01:00',
    '0070-01-01T00:00:00Z',
    '9999-12-31T23:00:00-05:00',
    ' 2026-11-02T10:00:00Z',
    '',
  ])('rejects %s', (input) => {
    expect(parseEventTimestamp(input)).toBeNull();
  });

  it.each([undefined, null, 1, {}, [], true])('rejects non-string %s', (v) => {
    expect(parseEventTimestamp(v)).toBeNull();
  });
});
